#[test]
fn file_names_and_extensions_map_as_in_0_4_0() {
    let registry = LanguageRegistry::with_builtins();
    for (path, expected) in PATHS {
        assert_eq!(
            registry.detect_path(Path::new(path)).as_str(),
            *expected,
            "{path}"
        );
    }
}

#[test]
fn content_sniffing_maps_as_in_0_4_0() {
    let registry = LanguageRegistry::with_builtins();
    for (head, expected) in HEADS {
        let detected = registry.detect_content(head.as_bytes());
        assert_eq!(
            detected.as_ref().map(LanguageId::as_str),
            *expected,
            "{head:?}"
        );
    }
}

#[test]
fn the_language_picker_lists_the_same_languages_in_the_same_order() {
    let registry = LanguageRegistry::with_builtins();
    let listed: Vec<_> = registry
        .descriptors()
        .into_iter()
        .map(|descriptor| (descriptor.id.as_str().to_owned(), descriptor.display_name))
        .collect();
    let expected: Vec<_> = PICKER
        .iter()
        .map(|(id, name)| ((*id).to_owned(), (*name).to_owned()))
        .collect();
    assert_eq!(listed, expected);
}

#[test]
fn comment_markers_are_unchanged() {
    let registry = LanguageRegistry::with_builtins();
    for (id, line, block) in COMMENTS {
        let syntax = registry.comment_syntax(&LanguageId::new(*id).expect("valid id"));
        assert_eq!(syntax.and_then(|syntax| syntax.line), *line, "{id} line");
        assert_eq!(syntax.and_then(|syntax| syntax.block), *block, "{id} block");
    }
}
